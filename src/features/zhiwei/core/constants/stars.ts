export const brightnessOf = (star: string, kind: StarKind, branch: number): string => {
  if (kind === 'major') return MAJOR_BRIGHTNESS[star]?.[branch] ?? ''
  if (kind === 'aux') {
    const v = AUX_BRIGHTNESS[star]?.[branch] ?? ''
    return v === '-' ? '' : v
  }
  if (MINOR_NO_BRIGHTNESS.has(star)) return ''
  return C5VUC_BRIGHTNESS_OVERRIDES[star]?.[branch] ?? P
}

